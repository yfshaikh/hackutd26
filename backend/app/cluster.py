"""Build the real cluster view (nodes, pods, GPU) from the live k3s cluster.

This file answers "what's actually running on the box right now?" and packages it into the
`Cluster` object the console draws as the data-center floor. It also seeds the list of
"assets" (the things worth protecting: the weights, the training job, the notebook, the node).

Everything here reads the cluster through the admin client. No synthetic data:
pods, cordon status, and GPU numbers all come from the API server and from
nvidia-smi run inside the platform telemetry pod.

Concepts (new here?):
  * nvidia-smi is NVIDIA's command-line tool that reports a GPU's utilization, memory and
    temperature. We run it inside a pod that has the GPU attached and parse its CSV output.
  * "Cordon" is a Kubernetes state meaning "don't schedule new pods on this node" (used by
    the defender to protect a node); you'll see cordon status surfaced to the UI here.
  * The "owner" label (owner=law-firm) is the trust signal: every legitimate workload carries
    it, so a pod WITHOUT it is, by definition, something the attacker created.
"""
from __future__ import annotations

from . import config
from .k8s import ApiException, admin, admin_apps, admin_core, admin_net, exec_in_pod, first_pod_name
from .models import (
    Asset,
    Cluster,
    ClusterNode,
    Gpu,
    Pod,
    PodCondition,
    PodContainerDetail,
    PodContainerPort,
    PodDetail,
    PodVolume,
    PodVolumeMount,
    PodWorkload,
    now_iso,
)

# Namespaces whose pods appear on the floor (the victim fleet + platform).
VISIBLE_NS = (config.LAWFIRM_NS, config.PLATFORM_NS)

NVIDIA_SMI = [
    "nvidia-smi",
    "--query-gpu=index,name,utilization.gpu,memory.used,memory.total,temperature.gpu",
    "--format=csv,noheader,nounits",
]


# --- Pod classification helpers -------------------------------------------
# These derive the fields the UI and the detector care about from a raw k8s pod.
def _pod_uses_gpu(pod) -> bool:
    for c in pod.spec.containers or []:
        res = c.resources
        for bag in (res.limits or {}, res.requests or {}):
            if "nvidia.com/gpu" in bag:
                return True
    return False


def _pod_mounts_weights(pod) -> bool:
    for v in pod.spec.volumes or []:
        if v.persistent_volume_claim and v.persistent_volume_claim.claim_name == config.MODEL_WEIGHTS_PVC:
            return True
    return False


def _owner_of(pod) -> str:
    # The owner label is the core trust signal: every legitimate workload carries
    # owner=law-firm or owner=platform. A pod with no (or an unknown) owner label is
    # what the detector flags as an intruder — attacker pods never set it.
    label = (pod.metadata.labels or {}).get("owner")
    if label == "law-firm":
        return "law-firm"
    if label == "platform":
        return "platform"
    return "unknown"


def _phase(pod) -> str:
    if pod.metadata.deletion_timestamp is not None:
        return "Terminating"
    phase = pod.status.phase if pod.status else "Pending"
    return phase if phase in ("Running", "Pending", "Succeeded", "Failed") else "Pending"


def _health_for_phase(phase: str) -> str:
    return {
        "Running": "healthy",
        "Pending": "degraded",
        "Succeeded": "healthy",
        "Failed": "critical",
        "Terminating": "degraded",
    }.get(phase, "degraded")


def quarantine_np_names() -> set[str]:
    """NetworkPolicies named quarantine-* currently in lawfirm."""
    try:
        nps = admin_net().list_namespaced_network_policy(config.LAWFIRM_NS)
    except ApiException:
        return set()
    return {np.metadata.name for np in nps.items if np.metadata.name.startswith("quarantine-")}


def list_pods() -> list[Pod]:
    core = admin_core()
    quarantined = quarantine_np_names()
    out: list[Pod] = []
    for ns in VISIBLE_NS:
        try:
            pods = core.list_namespaced_pod(ns)
        except ApiException:
            continue
        for p in pods.items:
            name = p.metadata.name
            phase = _phase(p)
            out.append(
                Pod(
                    name=name,
                    namespace=ns,
                    node=p.spec.node_name or "",
                    phase=phase,
                    owner=_owner_of(p),
                    usesGpu=_pod_uses_gpu(p),
                    health=_health_for_phase(phase),
                    quarantined=f"quarantine-{name}" in quarantined,
                )
            )
    return out


# --- Pod inspection -------------------------------------------------------
# Everything below feeds GET /cluster/pods/{namespace}/{name}; the console's floor
# drawer uses it to answer "what is this pod, what is it asking for, what is it
# saying?". Specs are read from the live Pod object. `summary` is generated by a
# small heuristic: a known app label first, then command text, then image. It is
# intentionally deterministic (no model call) so the floor stays fast and offline.
_APP_SUMMARY = {
    "model-server": "Serves the firm's fine-tuned contract model. It mounts the private "
                    "model-weights volume and holds one GPU.",
    "training": "Runs the firm's GPU fine-tuning job; it shares the T4 with whatever else "
                "is scheduled on the node.",
    "notebook": "A researcher's JupyterLab notebook, exposed through the edge proxy with "
                "auth disabled. It carries the over-privileged service-account token.",
    "notebook-edge": "Platform relay that exposes the notebook Service on the node's tailnet "
                     "address — the initial-access path.",
    "gpu-telemetry": "Platform telemetry agent. The command center execs nvidia-smi inside it "
                     "to read GPU utilization, memory and temperature.",
    "drop": "Attacker-controlled drop site: an HTTP server that accepts uploads and writes "
            "them to /loot.",
    "sink": "Attacker's in-cluster TCP sink, the target of the bounded egress flood.",
}


def _iso(value) -> str | None:
    """k8s datetimes are datetime objects; the wire wants ISO strings."""
    return value.isoformat() if value else None


# Annotations that can embed a whole object spec (env values included) — never sent to the console.
_HIDDEN_ANNOTATIONS = {"kubectl.kubernetes.io/last-applied-configuration"}


def _safe_annotations(values) -> dict[str, str]:
    return {k: v for k, v in _str_map(values).items() if k not in _HIDDEN_ANNOTATIONS}


def _str_map(values) -> dict[str, str]:
    return {str(k): str(v) for k, v in (values or {}).items() if v is not None}


def _resource_bag(res) -> dict[str, dict[str, str]]:
    out: dict[str, dict[str, str]] = {}
    for label in ("limits", "requests"):
        bag = getattr(res, label, None) if res else None
        if bag:
            out[label] = {str(k): str(v) for k, v in bag.items()}
    return out


def _container_state(cs) -> dict:
    """Flatten a V1ContainerStatus into the fields the drawer shows."""
    out = {
        "ready": bool(cs.ready) if cs else False,
        "restartCount": int(cs.restart_count or 0) if cs else 0,
        "state": "unknown",
        "stateReason": None,
        "startedAt": None,
        "finishedAt": None,
        "exitCode": None,
        "lastState": None,
        "lastExitCode": None,
    }
    if cs is None:
        return out
    for prefix, state in (("", cs.state), ("last", cs.last_state)):
        if not state:
            continue
        if state.running:
            info = {
                "state": "running",
                "stateReason": None,
                "startedAt": _iso(state.running.started_at),
                "finishedAt": None,
                "exitCode": None,
            }
        elif state.waiting:
            info = {
                "state": "waiting",
                "stateReason": state.waiting.reason or state.waiting.message,
                "startedAt": None,
                "finishedAt": None,
                "exitCode": None,
            }
        elif state.terminated:
            info = {
                "state": "terminated",
                "stateReason": state.terminated.reason or state.terminated.message,
                "startedAt": _iso(state.terminated.started_at),
                "finishedAt": _iso(state.terminated.finished_at),
                "exitCode": state.terminated.exit_code,
            }
        else:
            continue
        if prefix == "":
            out.update(info)
        else:
            out["lastState"] = info["state"]
            out["lastExitCode"] = info["exitCode"]
    return out


def _container_detail(container, statuses) -> PodContainerDetail:
    status = next((s for s in statuses if s.name == container.name), None)
    resources = _resource_bag(container.resources)
    env = [e.name for e in (container.env or []) if e.name]
    env_from: list[str] = []
    for ef in container.env_from or []:
        if ef.config_map_ref:
            env_from.append(f"configMap/{ef.config_map_ref.name}")
        elif ef.secret_ref:
            env_from.append(f"secret/{ef.secret_ref.name}")
    mounts = [
        PodVolumeMount(
            name=m.name,
            mountPath=m.mount_path,
            readOnly=bool(m.read_only),
            subPath=m.sub_path,
        )
        for m in (container.volume_mounts or [])
    ]
    ports = [
        PodContainerPort(
            name=p.name,
            containerPort=int(p.container_port),
            protocol=p.protocol or "TCP",
        )
        for p in (container.ports or [])
    ]
    state = _container_state(status)
    return PodContainerDetail(
        name=container.name,
        image=container.image or "",
        imagePullPolicy=container.image_pull_policy,
        command=list(container.command or []),
        args=list(container.args or []),
        ports=ports,
        resources=resources,
        env=env,
        envFrom=env_from,
        volumeMounts=mounts,
        **state,
    )


def _volume_detail(v) -> PodVolume:
    if v.config_map:
        return PodVolume(name=v.name, kind="configMap", source=v.config_map.name)
    if v.persistent_volume_claim:
        return PodVolume(
            name=v.name,
            kind="pvc",
            source=v.persistent_volume_claim.claim_name,
            readOnly=bool(v.persistent_volume_claim.read_only),
        )
    if v.secret:
        return PodVolume(name=v.name, kind="secret", source=v.secret.secret_name)
    if v.empty_dir is not None:
        return PodVolume(name=v.name, kind="emptyDir")
    if v.host_path:
        return PodVolume(name=v.name, kind="hostPath", source=v.host_path.path)
    if v.projected is not None:
        return PodVolume(name=v.name, kind="projected")
    return PodVolume(name=v.name, kind="other")


def _workload_of(pod) -> PodWorkload | None:
    refs = pod.metadata.owner_references or []
    if not refs:
        return None
    ref = refs[0]
    kind, name = ref.kind, ref.name
    # A Deployment creates a ReplicaSet, which creates the Pod. Walk one level so
    # the drawer names the thing a human actually deployed.
    if kind == "ReplicaSet":
        try:
            rs = admin_apps().read_namespaced_replica_set(name, pod.metadata.namespace)
            owners = rs.metadata.owner_references or []
            if owners:
                kind, name = owners[0].kind, owners[0].name
        except ApiException:
            pass
    return PodWorkload(kind=kind, name=name)


def _pod_summary(pod, owner: str, uses_gpu: bool) -> str:
    labels = pod.metadata.labels or {}
    ann = pod.metadata.annotations or {}
    if ann.get("description"):
        return str(ann["description"])
    app = str(labels.get("app") or labels.get("k8s-app") or "")
    if app in _APP_SUMMARY:
        return _APP_SUMMARY[app]

    containers = pod.spec.containers or []
    blob = " ".join(
        " ".join([*(c.command or []), *(c.args or []), c.image or ""]) for c in containers
    ).lower()
    prefix = (
        "No owner label, so the firm's platform did not create this pod. "
        if owner == "unknown"
        else ""
    )
    if "xmrig" in blob or "matmul" in blob:
        return prefix + ("Runs a GPU matrix-multiply loop disguised as 'xmrig' — the "
                         "cryptojacking workload. It requests one GPU and pins it near 100%.")
    if "/weights" in blob and any(x in blob for x in ("urllib", "method='put'", "requests.put")):
        return prefix + ("Reads the model-weights volume and uploads it to an external drop "
                         "site — the data-exfiltration workload.")
    if "egress-flood" in blob or ("socket" in blob and "connect" in blob):
        return prefix + ("Opens a bounded TCP connection flood against an in-cluster sink "
                         "(the egress-stress workload).")
    image = containers[0].image if containers else "an unknown image"
    asks = " and requests one GPU" if uses_gpu else ""
    return prefix + f"Runs {image}{asks}. No app label or annotation describes it further."


def build_pod_detail(namespace: str, name: str) -> PodDetail:
    """Read one Pod and flatten it into the shape the floor drawer consumes."""
    pod = admin_core().read_namespaced_pod(name, namespace)
    phase = _phase(pod)
    owner = _owner_of(pod)
    uses_gpu = _pod_uses_gpu(pod)
    quarantined = f"quarantine-{name}" in quarantine_np_names()
    statuses = (pod.status.container_statuses or []) if pod.status else []
    spec = pod.spec
    return PodDetail(
        name=name,
        namespace=namespace,
        node=spec.node_name or "",
        phase=phase,
        owner=owner,
        usesGpu=uses_gpu,
        health=_health_for_phase(phase),
        quarantined=quarantined,
        summary=_pod_summary(pod, owner, uses_gpu),
        workload=_workload_of(pod),
        serviceAccount=spec.service_account_name or "default",
        podIP=pod.status.pod_ip if pod.status else None,
        hostIP=pod.status.host_ip if pod.status else None,
        qosClass=pod.status.qos_class if pod.status else None,
        restartPolicy=spec.restart_policy,
        createdAt=_iso(pod.metadata.creation_timestamp),
        startTime=_iso(pod.status.start_time) if pod.status else None,
        labels=_str_map(pod.metadata.labels),
        annotations=_safe_annotations(pod.metadata.annotations),
        containers=[_container_detail(c, statuses) for c in (spec.containers or [])],
        volumes=[_volume_detail(v) for v in (spec.volumes or [])],
        conditions=[
            PodCondition(
                type=c.type,
                status=c.status,
                reason=c.reason,
                message=c.message,
                lastTransitionTime=_iso(c.last_transition_time),
            )
            for c in ((pod.status.conditions or []) if pod.status else [])
        ],
    )


# --- Live GPU telemetry ----------------------------------------------------
def read_gpus() -> tuple[list[Gpu], float]:
    """Exec nvidia-smi in the telemetry pod. Returns (gpus, total utilization).

    The backend runs off-cluster, so it can't see the GPU directly; instead it
    execs nvidia-smi inside the platform telemetry pod (which has GPU access) and
    parses the CSV. `total` is the max utilization across GPUs — the miner spike
    the detector watches for. Real numbers only, never synthetic."""
    pod = first_pod_name(admin(), config.PLATFORM_NS, config.TELEMETRY_LABEL)
    if not pod:
        return [], 0.0
    raw = exec_in_pod(admin(), config.PLATFORM_NS, pod, NVIDIA_SMI)
    gpus: list[Gpu] = []
    for line in raw.strip().splitlines():
        parts = [x.strip() for x in line.split(",")]
        if len(parts) < 6:
            continue
        try:
            idx, model, util, mem_used, mem_total, temp = parts[:6]
            gpus.append(
                Gpu(
                    index=int(idx),
                    model=model,
                    utilization=float(util),
                    memUsedGiB=round(float(mem_used) / 1024, 2),
                    memTotalGiB=round(float(mem_total) / 1024, 2),
                    tempC=float(temp),
                )
            )
        except ValueError:
            continue
    total = max((g.utilization for g in gpus), default=0.0)
    return gpus, total


def build_node(gpus: list[Gpu]) -> ClusterNode:
    core = admin_core()
    nodes = core.list_node().items
    node = nodes[0] if nodes else None
    if node is None:
        return ClusterNode(name="unknown", role="gpu-worker", health="unreachable",
                           cordoned=False, gpus=gpus, cpuPct=0.0)
    cap = node.status.capacity or {}
    role = "gpu-worker" if "nvidia.com/gpu" in cap else "control-plane"
    cordoned = bool(node.spec.unschedulable)
    ready = any(c.type == "Ready" and c.status == "True" for c in (node.status.conditions or []))
    return ClusterNode(
        name=node.metadata.name,
        role=role,
        health="healthy" if ready else "unreachable",
        cordoned=cordoned,
        gpus=gpus,
        cpuPct=0.0,
    )


def build_cluster(gpu_history: list[float], gpus: list[Gpu] | None = None) -> Cluster:
    if gpus is None:
        gpus, _total = read_gpus()
    node = build_node(gpus)
    return Cluster(name="winstead-gpu", nodes=[node], pods=list_pods(), gpuHistory=gpu_history)


# --- Protected assets (scope) ----------------------------------------------
def seed_assets() -> list[Asset]:
    """The protected assets, all clean at the start. Refs point at live objects.

    Returns the list; it does NOT write the store. main.py's startup seeds the
    store from this, and anything resetting scope must upsert these back in."""
    ts = now_iso()
    node_name = ""
    try:
        nodes = admin_core().list_node().items
        node_name = nodes[0].metadata.name if nodes else ""
    except ApiException:
        pass
    notebook = first_pod_name(admin(), config.LAWFIRM_NS, config.NOTEBOOK_LABEL) or "notebook"
    training = first_pod_name(admin(), config.LAWFIRM_NS, "app=training") or "training"
    return [
        Asset(
            id="model-weights",
            name="Fine-tuned model weights",
            kind="model-weights",
            description="contracts-ft-v3.pt — the firm's private fine-tuned contract model (~300 MB).",
            ref=f"pvc/{config.MODEL_WEIGHTS_PVC}",
            status="clean",
            statusSince=ts,
        ),
        Asset(
            id="training",
            name="Model training job",
            kind="job",
            description="Ongoing GPU fine-tuning run for the firm.",
            ref=f"pod/{training}",
            status="clean",
            statusSince=ts,
        ),
        Asset(
            id="notebook",
            name="Data-science notebook",
            kind="pod",
            description="A researcher's notebook. Holds an over-privileged service-account token.",
            ref=f"pod/{notebook}",
            status="clean",
            statusSince=ts,
        ),
        Asset(
            id="node",
            name="GPU node",
            kind="node",
            description="The single Tesla T4 node running all firm workloads.",
            ref=f"node/{node_name}",
            status="clean",
            statusSince=ts,
        ),
    ]
